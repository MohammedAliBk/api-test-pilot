using System.Reflection;
using System.Text;
using APITestPilot.Application;
using APITestPilot.Infrastructure.Persistence;
using FirebaseAdmin;
using Google.Apis.Auth.OAuth2;
using Microsoft.AspNetCore.Authentication.JwtBearer;
using Microsoft.IdentityModel.Tokens;
using Microsoft.OpenApi;
using Scalar.AspNetCore;

var builder = WebApplication.CreateBuilder(args);

// ─── 1. Firebase Admin SDK ────────────────────────────────────────────────────
var configuredFirebasePath = builder.Configuration["Firebase:CredentialsPath"];
string? firebaseKeyPath = null;

if (!string.IsNullOrEmpty(configuredFirebasePath))
{
    var candidatePaths = new[]
    {
        configuredFirebasePath,
        Path.Combine(builder.Environment.ContentRootPath, configuredFirebasePath),
        Path.Combine(builder.Environment.ContentRootPath, "..", configuredFirebasePath),
        Path.Combine(AppContext.BaseDirectory, configuredFirebasePath),
        Path.Combine(Directory.GetCurrentDirectory(), configuredFirebasePath)
    };
    firebaseKeyPath = candidatePaths.FirstOrDefault(File.Exists);
}

if (firebaseKeyPath == null)
{
    var candidateDirs = new[]
    {
        Path.Combine(builder.Environment.ContentRootPath, "Firebase"),
        Path.Combine(builder.Environment.ContentRootPath, "..", "Firebase"),
        Path.Combine(AppContext.BaseDirectory, "Firebase"),
        Path.Combine(Directory.GetCurrentDirectory(), "Firebase")
    };

    foreach (var dir in candidateDirs)
    {
        if (Directory.Exists(dir))
        {
            var match = Directory.GetFiles(dir, "*firebase*.json").FirstOrDefault()
                     ?? Directory.GetFiles(dir, "*.json").FirstOrDefault();
            if (match != null) { firebaseKeyPath = match; break; }
        }
    }
}

if (!string.IsNullOrEmpty(firebaseKeyPath) && File.Exists(firebaseKeyPath))
{
#pragma warning disable CS0618
    FirebaseApp.Create(new AppOptions { Credential = GoogleCredential.FromFile(firebaseKeyPath) });
#pragma warning restore CS0618
}
else if (!string.IsNullOrEmpty(Environment.GetEnvironmentVariable("GOOGLE_APPLICATION_CREDENTIALS")))
{
    FirebaseApp.Create(new AppOptions { Credential = GoogleCredential.GetApplicationDefault() });
}

// ─── 2. Application & Infrastructure Services ─────────────────────────────────
builder.Services.AddApplication();
builder.Services.AddPersistence(builder.Configuration);

// ─── 3. JWT Authentication ────────────────────────────────────────────────────
builder.Services.AddAuthentication(JwtBearerDefaults.AuthenticationScheme)
    .AddJwtBearer(options =>
    {
        options.TokenValidationParameters = new TokenValidationParameters
        {
            ValidateIssuer = true,
            ValidateAudience = true,
            ValidateLifetime = true,
            ValidateIssuerSigningKey = true,
            ValidIssuer = builder.Configuration["Jwt:Issuer"],
            ValidAudience = builder.Configuration["Jwt:Audience"],
            IssuerSigningKey = new SymmetricSecurityKey(
                Encoding.UTF8.GetBytes(builder.Configuration["Jwt:SecretKey"]!))
        };
    });

builder.Services.AddAuthorization();
builder.Services.AddControllers();

// ─── 4. OpenAPI — powers Scalar ───────────────────────────────────────────────
builder.Services.AddOpenApi();

// ─── 5. Swagger UI (classic) with XML docs + JWT Bearer ───────────────────────
builder.Services.AddSwaggerGen(options =>
{
    options.SwaggerDoc("v1", new OpenApiInfo
    {
        Title       = "API Test Pilot",
        Version     = "v1",
        Description = "Backend API for the API Test Pilot platform — AI-assisted API testing " +
                      "with intelligent test generation and resilient execution."
    });

    // Pull in the XML documentation file generated by the compiler
    var xmlFile = $"{Assembly.GetExecutingAssembly().GetName().Name}.xml";
    var xmlPath = Path.Combine(AppContext.BaseDirectory, xmlFile);
    if (File.Exists(xmlPath))
        options.IncludeXmlComments(xmlPath);

    // JWT Bearer security definition
    options.AddSecurityDefinition("Bearer", new OpenApiSecurityScheme
    {
        Name         = "Authorization",
        Description  = "Enter your JWT token below. Format: Bearer {your_token}",
        In           = ParameterLocation.Header,
        Type         = SecuritySchemeType.Http,
        Scheme       = "bearer",
        BearerFormat = "JWT"
    });
    options.AddSecurityRequirement(document => new OpenApiSecurityRequirement
    {
        [new OpenApiSecuritySchemeReference("Bearer", document)] = new List<string>()
    });
});

// ─────────────────────────────────────────────────────────────────────────────
var app = builder.Build();

if (app.Environment.IsDevelopment() || app.Environment.IsProduction() )
{
    // ── Scalar  →  http://localhost:{port}/scalar/v1 ──────────────────────────
    app.MapOpenApi();
    app.MapScalarApiReference(options =>
    {
        options.Title              = "API Test Pilot";
        options.Theme              = ScalarTheme.DeepSpace;
        options.DefaultHttpClient  = new(ScalarTarget.CSharp, ScalarClient.HttpClient);
        options.AddPreferredSecuritySchemes(new[] { "Bearer" });
    });

    // ── Swagger UI  →  http://localhost:{port}/swagger ───────────────────────
    app.UseSwagger();
    app.UseSwaggerUI(options =>
    {
        options.SwaggerEndpoint("/swagger/v1/swagger.json", "API Test Pilot v1");
        options.DisplayRequestDuration();
    });
}

app.UseHttpsRedirection();
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();
app.Run();
